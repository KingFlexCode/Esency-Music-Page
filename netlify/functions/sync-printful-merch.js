// netlify/functions/sync-printful-merch.js
// ========================================================
// SYNC PRINTFUL MERCH
// Fetches all products directly from Printful Manual API,
// groups them by product type, and updates product-map.js
// ========================================================

import fetch from "node-fetch";
import fs from "fs";

export async function handler() {
  try {
    console.log("🚀 Starting Printful merch sync...");

    // 1️⃣ Fetch product list directly from Printful API
    const res = await fetch("https://api.printful.com/store/products", {
      headers: {
        Authorization: `Bearer ${process.env.PRINTFUL_API_KEY}`,
      },
    });

    const data = await res.json();

    // 2️⃣ Handle bad responses from Printful
    if (!res.ok || !data.result) {
      console.error("❌ Printful API error:", data);
      return {
        statusCode: 500,
        body: JSON.stringify({
          success: false,
          error: "Invalid response from Printful API",
          details: data,
        }),
      };
    }

    console.log(`📦 Retrieved ${data.result.length} products from Printful.`);

    // 3️⃣ Group products by product type
    const grouped = {};
    for (const product of data.result) {
      const type = product.type || "Other";
      if (!grouped[type]) grouped[type] = [];

      grouped[type].push({
        id: product.id,
        name: product.name,
        image: product.thumbnail_url,
        variants: product.variants?.map((v) => ({
          id: v.id,
          name: v.name,
          size: v.size,
          color: v.color,
          price: v.retail_price,
          availability: v.availability_status,
        })),
      });
    }

    // 4️⃣ Create a formatted JavaScript file for local usage
    const outputPath = "./scripts/product-map.js";
    const outputContent = `/* AUTO-GENERATED BY sync-printful-merch.js */
/* Do not edit manually — run sync-printful-merch.js to update */
export const PRODUCT_MAP = ${JSON.stringify(grouped, null, 2)};
`;

    fs.writeFileSync(outputPath, outputContent);
    console.log(`✅ Updated ${outputPath} with ${Object.keys(grouped).length} categories.`);

    // 5️⃣ Return success JSON for Netlify endpoint
    return {
      statusCode: 200,
      body: JSON.stringify({
        success: true,
        message: "✅ Printful merch synced successfully!",
        categories: Object.keys(grouped).length,
        products: data.result.length,
      }),
    };
  } catch (err) {
    console.error("🔥 Sync error:", err);
    return {
      statusCode: 500,
      body: JSON.stringify({
        success: false,
        error: err.message,
      }),
    };
  }
}